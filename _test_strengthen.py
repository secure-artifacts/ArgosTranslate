import glossary_inflection as gi

tests = [
    ("Мне нравится книга.", "книга", "ru"),
    ("Я нравится книга.", "Мне", "ru"),
    ("Он работает в библиотека.", "библиотеке", "ru"),
    ("Он идет в библиотека.", "библиотеку", "ru"),
    ("Мы смотрим интересный фильм.", "фильм", "ru"),
    ("Он занимается собой.", "собой", "ru"),
    ("Я вижу студент и учитель.", "учителя", "ru"),
    ("Мені подобається книжка.", "книжка", "uk"),
    ("Я подобається книжка.", "Мені", "uk"),
    ("Мы не написали письмо.", "письма", "ru"),
    ("Он живет на улица.", "улице", "ru"),
    ("Лучше меня.", "меня", "ru"),
    ("У него нет денег.", "денег", "ru"),
    ("Он помогает друг.", "другу", "ru"),
    ("В комнате нет стул.", "стула", "ru"),
]
fail = 0
for s, k, lang in tests:
    r = gi.fix_sentence_slavic_morphology(s, lang)
    ok = k.lower() in r.lower()
    if not ok:
        fail += 1
    print("OK" if ok else "??", s, "=>", r)
print("failures:", fail)
